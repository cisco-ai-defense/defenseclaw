WIDTH = 100


def lit(text: str, indent: int) -> str:
    """A Python string literal for *text*, wrapped into lines that fit 120 columns."""
    if len(repr(text)) + indent <= 118:
        return repr(text)
    pieces: list[str] = []
    for line in text.splitlines(keepends=True):
        while len(line) > WIDTH:
            cut = line.rfind(" ", 0, WIDTH) + 1
            if cut <= 0:
                cut = WIDTH
            pieces.append(line[:cut])
            line = line[cut:]
        pieces.append(line)
    pad = " " * (indent + 4)
    body = "\n".join(pad + repr(piece) for piece in pieces)
    return "(\n" + body + "\n" + " " * indent + ")"


def render_flag(flag: dict, indent: int) -> str:
    parts = [repr(flag["name"]), repr(flag["type"]), lit(flag["usage"], indent + 4)]
    if flag.get("shorthand"):
        parts.append("short=" + repr(flag["shorthand"]))
    default = flag.get("default", "")
    if default and (flag["type"] != "bool" or default == "true") and default not in {"[]", "false"}:
        parts.append("default=" + repr(default))
    if flag.get("metavar"):
        parts.append("metavar=" + repr(flag["metavar"]))
    return " " * indent + "_Flag(" + ", ".join(parts) + "),"


def render_cmd(entry: dict) -> str:
    path = tuple(entry["path"].split()[1:])
    lines = ["    _Cmd("]
    lines.append("        " + repr(path) + ",")
    lines.append("        " + lit(entry["short"], 8) + ",")
    if entry.get("long"):
        lines.append("        long=" + lit(entry["long"], 13) + ",")
    if entry.get("example"):
        lines.append("        example=" + lit(entry["example"], 16) + ",")
    if entry.get("args"):
        args = ", ".join(
            "_Arg({}{}{})".format(
                repr(a["name"]),
                "" if a["required"] else ", required=False",
                ", many=True" if a.get("many") else "",
            )
            for a in entry["args"]
        )
        lines.append("        args=(" + args + ("," if len(entry["args"]) == 1 else "") + "),")
    if entry.get("flags"):
        lines.append("        flags=(")
        lines.extend(render_flag(f, 12) for f in entry["flags"])
        lines.append("        ),")
    lines.append("    ),")
    return "\n".join(lines)


