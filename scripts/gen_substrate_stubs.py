def ruff_format(text: str) -> str:
    """Format the module the way the repository does (ruff format), so the file passes the lint gate."""
    exe = shutil.which("ruff")
    cmd = [exe] if exe else [sys.executable, "-m", "ruff"]
    try:
        done = subprocess.run(
            [*cmd, "format", "--stdin-filename", str(TARGET), "-"],
            input=text,
            capture_output=True,
            text=True,
            check=False,
            cwd=REPO_ROOT,
        )
    except OSError:
        return text
    if done.returncode != 0 or not done.stdout:
        return text
    return done.stdout


def render() -> str:
    entries = json.loads(SOURCE.read_text(encoding="utf-8"))
    root = entries[0]
    assert root["path"] == "substrate", "the manifest starts with the root command"
    body = [HEADER.rstrip("\n"), ""]
    body.append("ROOT_SHORT = " + repr(root["short"]))
    body.append("ROOT_HELP = " + lit(root["long"], 12))
    body.append("")
    passthrough = [tuple(e["path"].split()[1:]) for e in entries[1:] if e.get("passthrough")]
    body.append("# Commands whose Go side parses its own flags.")
    body.append("PASSTHROUGH: frozenset[tuple[str, ...]] = frozenset(" + repr(sorted(passthrough)) + ")")
    body.append("")
    body.append("SUBSTRATE_COMMANDS: tuple[_Cmd, ...] = (")
    for entry in entries[1:]:
        body.append(render_cmd(entry))
    body.append(")")
    return ruff_format("\n".join(body) + "\n" + FOOTER)


