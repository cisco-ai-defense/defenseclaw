#!/usr/bin/env python3
"""mkrows.py FIXTURE_DIR CLASS:ID[,ID...] ... > rows.tsv
Writes class, row id, base64 script, the command names pwsh 7.6.6 reads (oracle view cn, lower-case, '|' joined)
and the parameters pwsh binds a -Name: value to (lower-case, '|' joined)."""
import sys, gzip, json
F = sys.argv[1]
want = {}
for a in sys.argv[2:]:
    c, ids = a.split(':', 1)
    for i in ids.split(','):
        want[i] = c
ids = [l.split('\t')[0] for l in open(F + '/pub.ids')]
idx = {ids[i]: i for i in range(len(ids)) if ids[i] in want}
b64 = {}
for i, l in enumerate(gzip.open(F + '/pub.b64.gz', 'rt')):
    if ids[i] in want:
        b64[ids[i]] = l.strip()
names, colon = {}, {}
for l in gzip.open(F + '/pub.oview.jsonl.gz', 'rt'):
    o = json.loads(l)
    rid = ids[o['i']]
    if rid in want:
        names[rid] = [(c.get('cn') or '').lower() for c in o['cmds'] if c.get('name') and c['name'][0] == 'bare' and c['name'][2]]
        colon[rid] = [e[1].lower() for c in o['cmds'] for e in c.get('el', []) if e[0] == 'param' and e[2]]
print('# class\trow id\tscript (base64, UTF-8)\tcommand names pwsh 7.6.6 reads (lower-case, | joined)\tparameters pwsh binds a -Name: value to (lower-case, | joined); generated by scripts/pwshoracle/mkrows.py from scripts/pwshoracle/fixture')
for rid, c in want.items():
    if rid not in b64:
        sys.exit('missing ' + rid)
    print('%s\t%s\t%s\t%s\t%s' % (c, rid, b64[rid], '|'.join(names.get(rid, [])), '|'.join(colon.get(rid, []))))
