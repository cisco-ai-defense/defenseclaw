def _option(flag: _Flag) -> GatewayOption:
    """The Click option of one flag; a Go duration is a string the gateway parses."""
    if flag.go_type != "duration":
        return _click_option(flag)
    decls = [f"--{flag.name}"]
    if flag.short:
        decls.append(f"-{flag.short}")
    return GatewayOption(
        decls,
        go_type="duration",
        go_default=flag.default or "0s",
        type=click.STRING,
        metavar=flag.metavar or None,
        help=flag.help,
    )


def exec_gateway(argv: Sequence[str]) -> NoReturn:
    """Replace this process with ``defenseclaw-gateway <argv>``."""
    from defenseclaw.gateway import GATEWAY_NOT_FOUND_MESSAGE, resolve_gateway_binary

    binary = resolve_gateway_binary()
    if not binary:
        raise click.ClickException(GATEWAY_NOT_FOUND_MESSAGE)
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.flush()
        except (OSError, ValueError):
            pass
    try:
        _execv(binary, [binary, *argv])
    except OSError as exc:
        ux.echo(f"could not start {binary}: {exc.strerror or exc}", err=True)
        raise SystemExit(1) from exc
    raise SystemExit(0)  # only reached when a test replaces _execv


def _forward(ctx: click.Context, **_params: Any) -> NoReturn:
    command = ctx.command
    assert isinstance(command, GatewayCommand)
    raw = ctx.meta.get(_RAW_ARGS_KEY, ())
    exec_gateway(("substrate", *command.gateway_path, *raw))


def _build_command(cmd: _Cmd) -> click.Command:
    if cmd.path in PASSTHROUGH:
        # The Go command parses its own flags (it hands them to another tool), so the stub forwards
        # every word, --help included.
        return GatewayCommand(
            cmd.path[-1],
            params=[click.Argument(["words"], nargs=-1, type=click.UNPROCESSED)],
            callback=click.pass_context(_forward),
            help=_help_text(cmd),
            short_help=cmd.short,
            gateway_path=cmd.path,
            context_settings={"ignore_unknown_options": True, "allow_extra_args": True, "help_option_names": []},
            no_args_is_help=False,
        )
    params: list[click.Parameter] = [_click_argument(arg) for arg in cmd.args]
    params += [_option(flag) for flag in cmd.flags]
    return _SubstrateCommand(
        cmd.path[-1],
        params=params,
        callback=click.pass_context(_forward),
        help=_help_text(cmd),
        short_help=cmd.short,
        gateway_path=cmd.path,
        no_args_is_help=False,
    )


def _build_group(cmd: _Cmd) -> click.Group:
    return click.Group(cmd.path[-1], help=_help_text(cmd), short_help=cmd.short)


