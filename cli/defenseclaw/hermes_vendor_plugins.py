"""Whether the installed Hermes is a release whose shipped plugins the gateway recognizes.

The gateway leaves a plugin in hermes-agent/plugins unscanned only while its
tree matches the digest of that plugin in a Hermes release DefenseClaw ships
digests for (internal/watcher/hermes_vendor_plugin_digests.go, regenerated by
scripts/hermes_vendor_plugin_digests.py; rel-1-0-10:GAP-0765). Doctor and
status use this module to say plainly when the installed Hermes is newer than
every such release, what that means and what to do.
"""

from __future__ import annotations

from dataclasses import dataclass

from defenseclaw.connector_contracts import normalize_agent_version
from defenseclaw.hermes_vendor_plugin_releases import NEWEST_PLUGIN_COUNT, RELEASES

COVERED = "covered"
NEWER = "newer"
OTHER = "other"


@dataclass(frozen=True)
class ShippedPluginCoverage:
    """``state`` is covered, newer, other, or empty when no version was read."""

    state: str
    version: str
    detail: str
    step: str = ""


def _key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


def _date_form(version: str) -> bool:
    # A Hermes git install prints only its release date (vunknown (2026.9.24)).
    return _key(version)[0] >= 2000


def _covered_versions() -> set[str]:
    covered: set[str] = set()
    for version, tag, _commit in RELEASES:
        covered.add(version)
        dated = normalize_agent_version(tag)
        if dated and _date_form(dated):
            covered.add(dated)
    return covered


def shipped_plugin_coverage(raw_version: str | None) -> ShippedPluginCoverage:
    """Say whether the shipped plugins of this Hermes version are recognized by digest."""

    version = normalize_agent_version(raw_version)
    oldest, newest = RELEASES[0][0], RELEASES[-1][0]
    span = f"Hermes {oldest} to {newest}"
    if not version:
        return ShippedPluginCoverage("", "", "the Hermes version was not read")
    if version in _covered_versions():
        return ShippedPluginCoverage(
            COVERED,
            version,
            f"Hermes {version} is a release DefenseClaw ships plugin digests for ({span}): "
            "its unchanged shipped plugins are vendor content and are not scanned; one that holds Python bytecode "
            "Hermes wrote is scanned once for that bytecode, not again for a scanner change; an edited one is scanned",
        )
    dates = [_key(v) for v in _covered_versions() if _date_form(v)]
    if _date_form(version):
        newer = bool(dates) and _key(version) > max(dates)
    else:
        newer = _key(version) > _key(newest)
    consequence = (
        "its shipped plugins in hermes-agent/plugins match no digest DefenseClaw ships, so the gateway "
        "scans each one as an unknown plugin when it starts and when they change, and refuses one with a "
        "HIGH finding like any other plugin"
    )
    if newer:
        return ShippedPluginCoverage(
            NEWER,
            version,
            f"Hermes {version} is newer than every Hermes release DefenseClaw ships plugin digests for "
            f"(newest {newest}, {NEWEST_PLUGIN_COUNT} shipped plugins): {consequence}",
            f"update DefenseClaw to a release that covers Hermes {version} (defenseclaw upgrade); "
            "until then these scans are expected, and defenseclaw alerts lists their findings",
        )
    return ShippedPluginCoverage(
        OTHER,
        version,
        f"Hermes {version} is not a Hermes release DefenseClaw ships plugin digests for ({span}): {consequence}",
        f"install a Hermes release from {oldest} to {newest} (the stable channel), or expect these scans",
    )
