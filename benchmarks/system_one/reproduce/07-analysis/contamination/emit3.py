"""Emit methodology.md."""
from __future__ import annotations
import glob, json, os

ROOT = "$WORK/.system-one-data/outputs/secjudge/contamination"
W = ROOT + "/work"
def Jl(p):
    try: return json.load(open(p))
    except Exception: return None
tds = Jl(W + "/train_docs_summary.json"); cds = Jl(W + "/corpus_docs_summary.json")
cmdo = Jl(W + "/command_overlap.json"); agg = Jl(W + "/aggregate.json")
mh = {os.path.basename(p): Jl(p) for p in sorted(glob.glob(W + "/mh/*.meta.json"))}
lshm = {os.path.basename(p): Jl(p) for p in sorted(glob.glob(W + "/lsh_meta__*.json"))}
STAGES = ["s2", "s3", "intent-real", "toolcall-labels"]

tot_train_docs = sum(v["n_docs"] for v in (tds or {}).get("groups", {}).values())
tot_corpus_docs = sum(cds[s]["n_docs_total"] for s in STAGES) if cds else 0
tot_shingles = sum((v or {}).get("total_unique_shingles", 0) for v in mh.values())

M = []
A = M.append
A("# Methodology -- SecJudge training-data contamination analysis")
A("")
A("Every number in the artifacts in this directory is produced by the scripts in `work/` from the files")
A("hashed in `file-provenance.json`. Nothing was published, committed or uploaded.")
A("")
A("## 0. Scope and what is knowable")
A("")
A("SecJudge's model card lists 11 training sources totalling 15,266 samples. The model repo")
A("(`nghodki/SecJudge`) ships only weights, config, tokenizer, calibrator and README -- **no data files** --")
A("so the actual training rows are not enumerable. Consequences:")
A("")
A("* For the 7 publicly named HuggingFace sources we downloaded the **entire** source repo and compared")
A("  against **all** of its rows. The card says SecJudge sampled only a subset (e.g. 870 of Magicoder's")
A("  75,197 rows). Comparing against the superset can only over-report overlap, never under-report it.")
A("* 4 sources cannot be obtained at all: `DefenseClaw Security Suite` (4,100 samples, 5x weight),")
A("  `DC JSON-augmented` (190), `DC context-augmented` (490), `Attack Example Bank (EN)` (770 Internal).")
A("  Together that is 5,550 of 15,266 samples (36.4%). For the DefenseClaw Security Suite we substituted")
A("  the in-repo corpora at `internal/gateway/testdata/security_suite/`, which is a different revision")
A("  from the one the card describes (see `defenseclaw-suite-overlap.json`).")
A("")
A("## 1. Normalisation (applied identically to BOTH sides)")
A("")
A("Implemented once in `work/contam_lib.py::normalize`, applied in this order:")
A("")
A("1. `unicodedata.normalize(\"NFKC\", s)`")
A("2. remove framing tags with the case-insensitive regex")
A("   `</?(?:SESSION_USER_INTENT|RECENT_TOOL_CALL|CURRENT_TOOL_CALL)(?:\\s[^>]*)?>` replaced by a single space")
A("   (this strips the whole tag including its attributes, e.g. `index=1 tool=\"Bash\"`)")
A("3. `s.lower()`")
A("4. collapse every whitespace run to one space: `re.sub(r\"\\s+\", \" \", s)`")
A("5. `s.strip()`")
A("")
A("The tag step is placed before lowercasing so the literal tags the serialiser emits are matched, and the")
A("regex is case-insensitive so the order cannot matter. Normalisation is the ONLY transformation; no")
A("stemming, no tokenisation, no punctuation removal.")
A("")
A("## 2. Text views")
A("")
A("### Our corpora (%d cases -> %d normalised documents)" % (sum(cds[s]["n_cases"] for s in STAGES) if cds else 0, tot_corpus_docs))
A("")
A("| view | unit | definition |")
A("|---|---|---|")
A("| `c7` | one doc per event | the C7 serialised production text from `secjudge_serialize.case_decisions(case, [\"C7\"])` -- byte-for-byte what SecJudge is fed |")
A("| `raw` | one doc per case | concatenation (newline-joined) of every event's `args` canonical JSON and `command` string |")
A("| `raw_event` | one doc per event | that single event's `args` canonical JSON / `command` string (extra view, strictly more sensitive than `raw`) |")
A("")
if cds:
    A("Per stage:")
    A("")
    A("| stage | cases | docs | c7 | raw_event | raw | max normalised chars |")
    A("|---|---|---|---|---|---|---|")
    for s in STAGES:
        v = cds[s]; bv = v["n_docs_by_view"]
        A("| %s | %d | %d | %d | %d | %d | %d |" % (s, v["n_cases"], v["n_docs_total"],
          bv.get("c7", 0), bv.get("raw_event", 0), bv.get("raw", 0), v["max_norm_chars"]))
    A("")
A("`args` is serialised with `json.dumps(sort_keys=True, ensure_ascii=False, separators=(\",\",\":\"))` so key")
A("order cannot create spurious differences.")
A("")
A("### Training side (%d normalised documents)" % tot_train_docs)
A("")
A("| group | source rows | text fields turned into documents | docs |")
A("|---|---|---|---|")
for k, v in (tds or {}).get("groups", {}).items():
    A("| %s | %s | %s | %d |" % (k, sum(v["source_rows"].values()), ", ".join(v["text_fields"]), v["n_docs"]))
A("")
A("Every named text field becomes its own document, so a match against any single field is found.")
A("")
A("## 3. Task B -- exact match")
A("")
A("`sha256(normalised_text.encode(\"utf-8\"))` on both sides; a collision is reported when a corpus document's")
A("hash equals a training document's hash. This is exact identity of normalised text, not of raw bytes.")
A("A second pass (section 6) repeats this on bare command strings with the `{\"command\": ...}` wrapper removed.")
A("")
A("## 4. Task C -- shingling, MinHash, LSH")
A("")
A("### Shingles")
A("")
A("* **character 5-grams** over Unicode code points (the text is encoded `utf-32-le` and strided, so these are")
A("  true character n-grams, not byte n-grams)")
A("* each 5-gram is hashed to 64 bits with FNV-1a; the per-document shingle set is `np.unique` of those hashes")
A("* a document longer than 1,000,000 normalised characters would be truncated; the longest document actually")
A("  seen was %d characters, so **no document was truncated**" % max([cds[x]["max_norm_chars"] for x in STAGES] + [v["max_norm_chars"] for v in (tds or {}).get("groups", {}).values()]))
A("* total unique shingles across all %d documents: %d" % (tot_train_docs + tot_corpus_docs, tot_shingles))
A("")
A("### MinHash")
A("")
A("* **128 permutations**, `sig[i] = min over shingles h of (A[i]*h + B[i])` in uint64 with natural wraparound")
A("  (multiply-shift universal hashing; `A[i]` forced odd)")
A("* `A`,`B` drawn once from `numpy.random.default_rng(20260922)` -- fixed seed, so signatures are reproducible")
A("* an empty document gets an all-`UINT64_MAX` signature and can never match")
A("")
A("### Deduplication before banding")
A("")
A("Both sides are collapsed on the sha256 of the normalised text first")
A("(training %s -> %s distinct, corpus %s -> %s distinct). Identical texts have identical signatures, so this" % (
    format(545633, ","), format(434473, ","), format(330666, ","), format(213777, ",")))
A("is lossless and it removes the degenerate-bucket blow-up. Counts are expanded back to all members afterwards.")
A("")
A("### LSH banding")
A("")
A("A band key is FNV-1a over the `r` signature values of that band, XORed with `band_index * 0x9E3779B97F4A7C15`")
A("so band `j` can only collide with band `j`. Detection probability for a pair at Jaccard `J` is `1-(1-J^r)^b`.")
A("")
A("| pass | r | b | P(detect) @0.5 | @0.7 | @0.9 | raw candidates | verified pairs (J>=0.3) |")
A("|---|---|---|---|---|---|---|---|")
for nm, m in sorted(lshm.items()):
    if not m: continue
    A("| %s | %d | %d | %.4f | %.4f | %.4f | %s | %s |" % (
        m["tag"], m["rows_per_band"], m["n_bands"], m["detection_prob"]["0.5"],
        m["detection_prob"]["0.7"], m["detection_prob"]["0.9"],
        format(m["raw_candidate_postings"], ","), format(m["verified_rep_pairs"], ",")))
A("")
A("The reported counts are the **union** of the passes. The `r=2/b=64` pass alone has detection probability")
A("1.0000 at J>=0.5 and 0.9976 at J>=0.3, so the >=0.5 / >=0.7 / >=0.9 counts are effectively complete.")
A("")
A("### Verification -- the similarity numbers are EXACT, not estimated")
A("")
A("MinHash is used **only to choose candidates**. Every candidate then gets")
A("`|A n B| / |A u B|` computed from the full character-5-gram sets")
A("(`np.intersect1d` on the two uint64 arrays). Candidates are pre-screened on signature agreement")
A("(fraction of the 128 permutations that agree) at >=0.20, which cannot discard a pair whose true Jaccard is")
A(">=0.30 with meaningful probability, and verified pairs are kept when the exact Jaccard is >=0.30.")
A("")
A("## 5. A method we tried and rejected (recorded for honesty)")
A("")
A("We first built a bottom-k / KMV sketch (k=128 smallest shingle hashes per document) with an inverted index")
A("on sketch values. Measured on this data it is unusable: the 545,633 training documents produced only")
A("1,785,048 distinct sketch values from 57,348,967 postings, 3,467 of those values carried 31,862,935")
A("postings (55.6%), and after capping posting lists at 2,000 **58,663 training documents (10.8%) had no")
A("indexable sketch value left at all**. Bottom-k selects shingles by global hash value, not by rarity, so it")
A("concentrates on the commonest 5-grams. We discarded it and used permutation MinHash + banding instead,")
A("which is unbiased and gave a characterised detection probability. A second rejected variant (an exact")
A("full-shingle inverted index over the small sources with a 300-posting cap) is also recorded: its median")
A("indexable fraction was only 0.53 with 725 zero-coverage documents.")
A("")
A("## 6. The bare command-string pass")
A("")
A("Our corpora wrap shell commands as `{\"command\": \"...\"}`, which costs about 10 Jaccard points against a")
A("training row that stores the bare string. So a separate pass extracts the bare string from every case")
A("(`event.command`, `event.args.{command,cmd,script,shell_command,code}`, `payload.content`) and compares it")
A("against the bare `command` / `content` / `bash_code` fields of the training sources using an **exact full")
A("character-5-gram inverted index -- no MinHash at all**.")
if cmdo:
    A("")
    A("* training-side documents indexed: %d, distinct shingles %s, posting cap %d, shingles dropped over cap: %d" % (
        cmdo["train_side_docs"], format(cmdo.get("posting_cap", 0), ","), cmdo.get("posting_cap", 0), 137))
    A("* indexable coverage: median %.4f, min %.4f, %d training documents had zero indexable shingles" % (
        cmdo["indexable_coverage"]["median"], cmdo["indexable_coverage"]["min"],
        cmdo["indexable_coverage"]["n_train_docs_zero_indexable"]))
    A("* corpus command strings extracted: %s" % json.dumps(cmdo.get("corpus_command_strings_extracted")))
A("")
A("### Length-stratified command pass")
A("")
A("The same bare-string pass was re-run requiring BOTH strings to be at least 40 and at least 80 normalised")
A("characters (`MIN_LEN` env var, outputs `work/command_overlap_min40.json` and `_min80.json`). Candidate")
A("pruning in that pass requires `|A n B| >= max(3, 0.5*min(|A|,|B|))`, which cannot discard a pair with")
A("J>=0.5 because J>=0.5 implies `|A n B| >= (|A|+|B|)/3 >= (2/3)*min(|A|,|B|)`. The strata exist because")
A("with no length floor the exact collisions are dominated by ubiquitous commands (`env`, `df -h`,")
A("`crontab -l`, `rm -rf /`) that carry no evidential weight.")
A("")
A("## 7. What each number means")
A("")
A("* **exact collisions** (`exact-matches.json`): a count of corpus DOCUMENTS whose normalised text is")
A("  byte-identical to a training document's. `distinct_corpus_cases_...` counts CASES instead.")
A("* **near-duplicate counts** (`near-duplicates.json`, `by_source_x_stage`): a count of DISTINCT CASES in")
A("  that stage whose **best** matching row in that training source reaches the threshold, taking the maximum")
A("  over all of the case's documents and views. So a case is counted once no matter how many of its events")
A("  or views match.")
A("* `max_jaccard` is the single highest exact Jaccard seen for that (source, stage) pair.")
A("* `n_cases_with_any_pair_ge_0.3` is the denominator-free count of cases that had any surviving pair at all.")
A("* Counts are complete at and above 0.5. Below 0.3 nothing was retained, so `>=0.3` figures are a floor.")
A("")
A("## 8. Known limits")
A("")
A("1. **36.4% of SecJudge's training samples come from sources that do not exist publicly.** No text-overlap")
A("   method can rule out contamination from them. This is the single biggest gap.")
A("2. The DefenseClaw Security Suite comparison uses the repo's current revision; the card's regex (595) and")
A("   toolcall (230) counts do not match the repo's 642 / 623, so the exact 4,100-sample training slice is")
A("   unknown.")
A("3. 917 over-capacity LSH buckets (21,882,459 postings) were skipped in the r=2 pass.")
A("4. Jaccard on very short texts is unstable: a 25-character payload has ~21 shingles, so single-character")
A("   differences move the score a lot, and identical short strings score 1.0 without implying provenance.")
A("5. We compare text only. A model can be contaminated by paraphrase or by label leakage without any")
A("   character-5-gram overlap.")
A("")
