#!/usr/bin/env python3
"""Conform the two settled Gemma-4 S2 arms to the Space build's added-arm contract.

The runs themselves are finished and are not touched: the prediction files, their settled
metas and the scorecards' contents are read, never rewritten.  What this does is put each
artifact at the path `src/build.py :: added_rel()` resolves, in the schema the published arms
already use, deriving every field from an artifact rather than declaring it:

  <dir>/<pred>.serving.json          gains the nested `served` / `serving` blocks the build
                                     reads, composed from the flat keys already in the file
                                     plus the run meta.  No flat key is removed or changed.
  <dir>/scores/s2-<pred>.json        the arm's scorecard, byte-identical to the run's own
  <dir>/scores/s2-<pred>.closure     closure / culling ledgers, byte-identical apart from the
  <dir>/scores/s2-<pred>.culling      two output paths, which are rewritten to the new names
                                     and re-checked against the digests they already record.
  {ADDED_VALID}/auc-variants-<pred>  regenerated by sysone-auc_variants.py, the same script
                                     that produced the three published arms' files, so the
                                     cross-arm comparison the build generates from these
                                     compares one definition of each variable rather than two.
  {ADDED_VALID}/mapping-check-<pred> regenerated by sysone-mapping_check.py, likewise.

Run with --check to verify without writing.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys

DATA = "$WORK/.system-one-data/outputs"
CASES = f"{DATA}/s2/cases.jsonl"
CASES_SHA = "39f2c1df2369952a0525cc4c5575f4bdb590fb3ca8c1bc6805cf4f376c1adbf7"
VALID = "openjev-qwen/validation"
ARM_DIR = "gemma4jev/s2"
AUC_GEN = "$WORK/sysone-auc_variants.py"
MAP_GEN = "$WORK/sysone-mapping_check.py"

# pred stem -> (display name as the run meta records it, the run's own score/closure/culling stems)
ARMS = [
    {"pred": "gemma-4-26b-a4b-it", "name": "gemma-4-26B-A4B-it", "stem": "arm2-base-temp"},
    {"pred": "jevify-gemma4-26b-a4b", "name": "jevify-gemma4-26b-a4b", "stem": "arm3-jevify"},
]

CHANGED: list[str] = []
NOTES: list[str] = []


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load(path: str):
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def write_json(path: str, obj, check: bool) -> None:
    body = json.dumps(obj, indent=2, sort_keys=True) + "\n"
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as fh:
            if fh.read() == body:
                return
    CHANGED.append(path)
    if check:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(body)


def write_bytes(path: str, body: bytes, check: bool) -> None:
    if os.path.exists(path) and open(path, "rb").read() == body:
        return
    CHANGED.append(path)
    if check:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(body)


def must(cond: bool, msg: str) -> None:
    if not cond:
        raise SystemExit(f"ABORT: {msg}")


# ----------------------------------------------------------------- serving.json


def build_serving(arm: dict, check: bool) -> None:
    """Add `served` and `serving` to the flat serving record, from the flat keys plus the meta.

    Every value is copied or composed from something already on disk.  The two blocks the
    build reads are the only addition; the flat keys the run's own tooling wrote stay exactly
    as they are, because other assertions read them.
    """
    pred = arm["pred"]
    spath = f"{DATA}/{ARM_DIR}/{pred}.serving.json"
    mpath = f"{DATA}/{ARM_DIR}/{pred}.jsonl.meta.json"
    flat, meta = load(spath), load(mpath)
    ms = meta["serving"]

    # the two records must already agree about what was served; if they do not, the run's own
    # provenance is inconsistent and nothing derived from it can be published
    must(flat["repo_id"] == meta["repo_id"],
         f"{pred}: serving repo_id {flat['repo_id']!r} != meta repo_id {meta['repo_id']!r}")
    must(flat["revision"] == meta["model_revision"],
         f"{pred}: serving revision != meta model_revision")
    must(flat["chat_template_sha256"] == ms["chat_template_sha256"],
         f"{pred}: chat template digest differs between the serving record and the meta")
    must(flat["temperature"] == meta["temperature"] == ms["temperature"],
         f"{pred}: temperature differs between the serving record and the meta")
    must(flat["prefix_cache"] is False and ms["prefix_cache"] is False,
         f"{pred}: prefix cache is not recorded as disabled")
    must(all("NVIDIA" in gpu for gpu in flat["gpus"]),
         f"{pred}: serving record names a non-NVIDIA device")
    must(len(flat["gpus"]) == len(flat["placement"]),
         f"{pred}: {len(flat['gpus'])} GPUs but {len(flat['placement'])} placement entries")

    ngpu = len(flat["gpus"])
    layers = {k: flat["placement"][k] for k in sorted(flat["placement"], key=int)}
    # the readout column's subject: what was served on top of the base weights, and how the
    # decision is read off it. Both halves are strings the run itself recorded.
    adapter = meta["adapter"]
    served = {
        "repo_id": flat["repo_id"],
        "repo_revision": flat["revision"],
        "base_model": meta["base_model"],
        "base_revision": meta["base_revision"],
        "adapter": adapter,
        "adapter_revision": meta["adapter_revision"],
        "architecture": (f"{adapter}; {ms['readout']}" if adapter
                         else f"no adapter, the base weights served directly; {ms['readout']}"),
        "readout": ms["readout"],
        "readout_kind": ms["readout_kind"],
        "loader": meta["loader"],
        "forward_passes_per_q2_decision": meta["forward_passes_per_decision"],
        "max_length": flat["max_input_tokens"],
        "temperature": flat["temperature"],
        "temperature_note": ms["temperature_note"],
        "attention": flat["attention"],
        "dtype": flat["dtype"],
        "chat_template_sha256": flat["chat_template_sha256"],
        "weight_sha256": meta["weight_sha256"],
        "pinned_stack": {"torch": flat["torch"], "cuda": flat["cuda"]},
    }
    serving = {
        "engine": ms["engine"],
        "gpu": f"{ngpu}x {ms['gpu']}",
        "gpu_count": ngpu,
        "gpu_models": list(flat["gpus"]),
        # one served instance per arm, split over its GPUs by device_map rather than replicated:
        # there is a single url, a single device_map and a single layer placement in the record.
        "replicas": 1,
        "topology": (f"1 replica sharded across {ngpu} GPUs "
                     f"(transformers device_map={flat['device_map']})"),
        "sharding": (f"single replica; transformers device_map={flat['device_map']} places "
                     f"{sum(layers.values())} decoder layers across {ngpu} GPUs "
                     + ", ".join(f"device {k}: {v} layers" for k, v in layers.items())
                     + f", {flat['max_gpu_memory']} cap per device; no tensor parallelism and "
                       f"no corpus stride sharding"),
        "layer_placement": layers,
        "max_gpu_memory": flat["max_gpu_memory"],
        "cuda_visible_devices": ms["cuda_visible_devices"],
        "prefix_cache": flat["prefix_cache"],
        "prefix_cache_reason": ms["prefix_cache_note"],
        "attention_reason": ms["attention_note"],
        "transport": ("POST on 127.0.0.1 loopback, jev.api/jev.server wire contract; "
                      "no port exposed publicly"),
        "relationship_to_incumbent": ms["relationship_to_incumbent"],
        "same_base_weights_as_incumbent_judge": ms["same_base_weights_as_incumbent_judge"],
    }
    out = dict(flat)
    for k, v in (("kind", "defenseclaw-system-one-serving-provenance"),
                 ("schema_version", "1"), ("stage", "s2"),
                 ("grid", "/".join(meta[j][0] for j in ("contexts", "instructions", "questions"))),
                 ("served", served), ("serving", serving)):
        out[k] = v
    # the display name the build keys the row on is the meta's; the flat record wrote the
    # lower-cased served model id into the same field, so it is corrected to the meta's value
    # and the served id is kept under its own key rather than dropped.
    if flat.get("display_name") != meta["display_name"]:
        NOTES.append(f'{pred}: serving.display_name {flat.get("display_name")!r} -> '
                     f'{meta["display_name"]!r} (the run meta\'s value); the served model id '
                     f'stays on `model`')
        out["display_name"] = meta["display_name"]
    for k in flat:
        if k not in ("display_name",):
            must(out[k] == flat[k], f"{pred}: flat serving key {k!r} would have changed")
    write_json(spath, out, check)


# ------------------------------------------------------------------- scorecards


def build_scores(arm: dict, check: bool) -> None:
    pred, stem = arm["pred"], arm["stem"]
    sdir = f"{DATA}/{ARM_DIR}/scores"
    src_score = f"{sdir}/score-{stem}.json"
    src_clos = f"{sdir}/closure-{stem}.json"
    src_cull = f"{sdir}/culling-{stem}.json"
    dst_score = f"{sdir}/s2-{pred}.json"
    dst_clos = f"{sdir}/s2-{pred}.closure.json"
    dst_cull = f"{sdir}/s2-{pred}.culling.json"

    closure = load(src_clos)
    # the closure already records the digest of each file it points at; check it against the
    # bytes on disk before those bytes are republished under another name
    must(closure["score_sha256"] == sha256_file(src_score),
         f"{pred}: closure score_sha256 does not match {src_score}")
    must(closure["culling_sha256"] == sha256_file(src_cull),
         f"{pred}: closure culling_sha256 does not match {src_cull}")
    must(closure["score_output"] == src_score and closure["culling_output"] == src_cull,
         f"{pred}: closure points at unexpected outputs")
    must(closure["cases_sha256"] == CASES_SHA, f"{pred}: closure ran another corpus")
    must(closure["complete"] is True, f"{pred}: closure is not complete")

    score = load(src_score)
    must(score["cases_sha256"] == CASES_SHA, f"{pred}: scorecard ran another corpus")
    must(list(score["prediction_sha256"]) == [f"{DATA}/{ARM_DIR}/{pred}.jsonl"],
         f"{pred}: scorecard scored another prediction file")
    must("candidates" in score and len(score["candidates"]) == 1
         and "binary_block_only" in score["candidates"][0]["deterministic_then_system_one"],
         f"{pred}: scorecard has no candidates[0] in the shape the build reads")

    # the scorecard and the culling ledger are republished byte for byte: the digests the
    # closure records stay true of the new paths.
    body = open(src_score, "rb").read()
    write_bytes(dst_score, body, check)
    write_bytes(dst_cull, open(src_cull, "rb").read(), check)
    moved = dict(closure)
    moved["score_output"] = dst_score
    moved["culling_output"] = dst_cull
    write_json(dst_clos, moved, check)
    if not check:
        must(sha256_file(dst_score) == closure["score_sha256"],
             f"{pred}: republished scorecard does not match the digest the closure records")
        must(sha256_file(dst_cull) == closure["culling_sha256"],
             f"{pred}: republished culling ledger does not match its recorded digest")


# ------------------------------------------------------- validation-side artifacts


def build_validation(arm: dict, check: bool) -> None:
    pred, name = arm["pred"], arm["name"]
    preds = f"{DATA}/{ARM_DIR}/{pred}.jsonl"
    for gen, out, extra in (
            (AUC_GEN, f"{DATA}/{VALID}/auc-variants-{pred}.json", ["--label", name]),
            (MAP_GEN, f"{DATA}/{VALID}/mapping-check-{pred}.json", [])):
        tmp = out + ".regen"
        cmd = [sys.executable, gen, "--cases", CASES, "--predictions", preds, "--out", tmp]
        r = subprocess.run(cmd + extra, capture_output=True, text=True)
        if r.returncode != 0:
            raise SystemExit(f"ABORT: {gen} failed for {pred}:\n{r.stderr}")
        body = open(tmp, "rb").read()
        os.remove(tmp)
        write_bytes(out, body, check)
    # the AUC file must carry the three variables the build reads and the fourth the published
    # files carry, or the score-variable table's columns would not line up across arms
    auc = json.loads(open(f"{DATA}/{VALID}/auc-variants-{pred}.json").read()
                     if not check or os.path.exists(f"{DATA}/{VALID}/auc-variants-{pred}.json")
                     else "{}")
    if auc:
        want = {"risk = 1 - P(allow)  [leaderboard variable]", "P(block)",
                "P(block) + P(confirm)", "P(block) - P(confirm)"}
        must(set(auc["auc"]) == want, f"{pred}: auc-variants keys {sorted(auc['auc'])}")
        must(auc["positives_A_B"] == 436 and auc["negatives_D"] == 3381,
             f"{pred}: auc-variants label counts differ from the corpus")
        must(auc["model"] == name, f"{pred}: auc-variants model {auc['model']!r} != {name!r}")


# ------------------------------------------------------------ the comparison table

CMP = f"{DATA}/{VALID.rsplit('/', 1)[0]}/s2/comparison-s2.json"
CMP_BAK = CMP + ".bak-before-gemma4-arms"
# which scorecard node each ranked cell is taken from. The three arms already published took
# their any-intervention and confirm-rate cells from the rules-then-model node, which is the node
# the Space's leaderboard reads for an added row; the Gemma-4 rows were assembled from the
# model-alone node instead, so the same field name held two different measurements across the
# table and the Space build's cell-for-cell cross-check rejected them. The model-alone values are
# not discarded: they move to their own keys, which is where the arm's own row already keeps the
# other node's block cells.
NODE = "deterministic_then_system_one"
ALT_NODE = "system_one"
CMP_CELLS = [("any_f1", "binary", "f1"), ("any_precision", "binary", "precision"),
             ("any_recall", "binary", "recall")]


def build_comparison_rows(check: bool) -> None:
    table = load(CMP)
    must(os.path.exists(CMP_BAK), "the pre-gemma4 backup of the comparison table is missing")
    baseline = {r["model"]: r for r in load(CMP_BAK)["rows"]}
    rows = table["rows"]
    must(len(rows) == 9, f"comparison table holds {len(rows)} rows, expected 9")
    names = {a["name"] for a in ARMS}
    for row in rows:
        if row["model"] not in names:
            must(row == baseline.get(row["model"]),
                 f'{row["model"]}: row differs from the pre-gemma4 backup and must not')
            continue
        arm = next(a for a in ARMS if a["name"] == row["model"])
        c = load(f"{DATA}/{ARM_DIR}/scores/s2-{arm['pred']}.json")["candidates"][0]
        # On the first pass the cell still holds the model-alone value; on a re-run it holds the
        # rules-then-model value and the model-alone one sits under its own key. Either state is
        # accepted, anything else means the row came from somewhere this does not understand.
        for key, lens, metric in CMP_CELLS + [("review_rate", None, "review_rate")]:
            alt = c[ALT_NODE]["review_rate"] if lens is None else c[ALT_NODE][lens][metric]
            node = c[NODE]["review_rate"] if lens is None else c[NODE][lens][metric]
            altkey = f"{ALT_NODE}_{key}"
            must(abs(row[key] - alt) < 5e-9
                 or (abs(row[key] - node) < 5e-9 and abs(row.get(altkey, -1) - alt) < 5e-9),
                 f'{row["model"]}: {key} {row[key]!r} is neither the model-alone value {alt!r} '
                 f'nor the rules-then-model value {node!r} with the model-alone one recorded '
                 f'beside it, so its provenance is not what this assumes')
            row[altkey] = alt
            row[key] = node
        # the cells that are the same measurement on both nodes, checked rather than assumed
        for key, lens, metric in (("block_f1", "binary_block_only", "f1"),
                                  ("block_precision", "binary_block_only", "precision"),
                                  ("block_recall", "binary_block_only", "recall"),
                                  ("block_fpr", "binary_block_only", "false_positive_rate"),
                                  ("any_fpr", "binary", "false_positive_rate")):
            must(abs(c[NODE][lens][metric] - c[ALT_NODE][lens][metric]) < 5e-9,
                 f'{row["model"]}: {key} differs between the two nodes, so it cannot be left '
                 f'in a column that means one of them')
            must(abs(row[key] - c[NODE][lens][metric]) < 5e-9,
                 f'{row["model"]}: {key} disagrees with its own scorecard')
        must(abs(row["three_way"] - c[NODE]["three_way"]["accuracy"]) < 5e-9,
             f'{row["model"]}: three_way disagrees with its own scorecard')
        row["cells_from_node"] = f"candidates[0].{NODE}"
        row["settled"] = True
    write_json(CMP, table, check)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    must(sha256_file(CASES) == CASES_SHA, "the corpus on disk is not the one the runs scored")
    for arm in ARMS:
        meta = load(f"{DATA}/{ARM_DIR}/{arm['pred']}.jsonl.meta.json")
        must(meta["display_name"] == arm["name"],
             f"{arm['pred']}: meta display_name {meta['display_name']!r} != {arm['name']!r}")
        must(meta["complete"] is True and meta["settled"] is True, f"{arm['pred']}: not settled")
        must(meta["prediction_sha256"] == sha256_file(f"{DATA}/{ARM_DIR}/{arm['pred']}.jsonl"),
             f"{arm['pred']}: prediction_sha256 does not match the bytes on disk")
        must(not meta["errors_by_code"], f"{arm['pred']}: run recorded errors")
        must(meta["requests"] == meta["rows_on_disk"] == 30310, f"{arm['pred']}: row count")
        build_serving(arm, args.check)
        build_scores(arm, args.check)
        build_validation(arm, args.check)
    build_comparison_rows(args.check)
    for n in NOTES:
        print("note:", n)
    verb = "would write" if args.check else "wrote"
    if CHANGED:
        print(f"{verb} {len(CHANGED)} file(s):")
        for p in CHANGED:
            print("  " + p)
    else:
        print("nothing to do: every conformed artifact is already on disk and identical")
    return 0


if __name__ == "__main__":
    sys.exit(main())
