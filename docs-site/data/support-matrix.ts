export function withUnlistedPreview(statuses: Record<OsId, Status>, unlisted: boolean | undefined): Record<OsId, Status> {
  if (!unlisted) return statuses;
  const out = { ...statuses };
  for (const os of OS_IDS) if (out[os] === 'not-offered') out[os] = 'preview';
  return out;
}

const CODE: Record<string, Status> = {
  S: 'supported',
  P: 'preview',
  U: 'unsupported',
  N: 'not-offered',
};

function decode(code: string | undefined, where: string): Status {
  const status = code ? CODE[code] : undefined;
  if (!status) throw new Error(`support-matrix: bad status code ${JSON.stringify(code)} for ${where}`);
  return status;
}

function perOs(codes: string, where: string): Record<OsId, Status> {
  const letters = codes.replace(/\s+/g, '');
  if (letters.length !== 3) throw new Error(`support-matrix: ${where} needs 3 status letters, got ${codes}`);
  return {
    linux: decode(letters[0], `${where} linux`),
    macos: decode(letters[1], `${where} macos`),
    windows: decode(letters[2], `${where} windows`),
  };
}

