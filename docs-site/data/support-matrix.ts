export interface ConnectorOsCell {
  status: Status;
  // Pre-execution block on this OS: capability-matrix hooks.canBlock, unless unsupported.
  block: boolean;
  // DefenseClaw telemetry verified reaching an OTLP back end (Grafana) and Galileo.
  observability: Status;
  note?: string;
}

export interface ConnectorRow {
  id: string;
  label: string;
  integration: Integration;
  minVersion: string;
  versionNote?: string;
  canAskNative: boolean;
  supportsFailClosed: boolean;
  oss: Record<OsId, ConnectorOsCell>;
  enterprise: Record<OsId, { route: Route; status: Status }>;
  routeNote?: string;
}

function buildConnector(source: ConnectorSource): ConnectorRow {
  const cap = capabilityById.get(source.id);
  const ossCodes = generated.oss[source.id];
  const entCodes = generated.enterprise[source.id];
  if (!cap || !ossCodes || !entCodes) throw new Error(`support-matrix: missing data for ${source.id}`);
  const pairs = ossCodes.trim().split(/\s+/);
  if (pairs.length !== 3) throw new Error(`support-matrix: ${source.id} needs 3 OSS cells`);
  const entStatus = perOs(entCodes, `${source.id} enterprise`);
  const oss = {} as Record<OsId, ConnectorOsCell>;
  const enterprise = {} as ConnectorRow['enterprise'];
  const currentStatus = (status: Status): Status => source.preview && status === 'supported' ? 'preview' : status;
  OS_IDS.forEach((os, i) => {
    const status = currentStatus(decode(pairs[i][0], `${source.id} ${os}`));
    oss[os] = {
      status,
      block: cap.hooks.canBlock && status !== 'unsupported',
      observability: currentStatus(decode(pairs[i][1], `${source.id} ${os} observability`)),
      note: source.notes?.[os],
    };
    const route = source.route[os];
    enterprise[os] = { route, status: route === 'unsupported' ? 'unsupported' : currentStatus(entStatus[os]) };
  });
  return {
    id: source.id,
    label: cap.label,
    integration: source.integration,
    minVersion: source.minVersion,
    versionNote: source.versionNote,
    canAskNative: cap.hooks.canAskNative,
    supportsFailClosed: cap.hooks.supportsFailClosed,
    oss,
    enterprise,
    routeNote: source.routeNote,
  };
}

