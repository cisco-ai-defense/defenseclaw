//go:build !windows

package main

import (
	"os"
	"syscall"
)

// lifecycleHelperProcessAlive reports whether pid is a running process.
func lifecycleHelperProcessAlive(pid int) bool {
	process, err := os.FindProcess(pid)
	if err != nil {
		return false
	}
	return process.Signal(syscall.Signal(0)) == nil
}
