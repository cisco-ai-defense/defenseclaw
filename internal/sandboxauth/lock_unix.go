//go:build !windows

package sandboxauth

import (
	"fmt"
	"os"
	"syscall"
)

const lockSupported = true

// lockExclusive takes an advisory exclusive lock on path. The lock file is
// never deleted: unlinking a lock file lets a waiter and a newcomer lock two
// different inodes at once.
func lockExclusive(path string) (func(), error) {
	f, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR|syscall.O_NOFOLLOW, 0o600)
	if err != nil {
		return nil, fmt.Errorf("sandboxauth: open binding lock: %w", err)
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX); err != nil {
		_ = f.Close()
		return nil, fmt.Errorf("sandboxauth: acquire binding lock: %w", err)
	}
	return func() {
		_ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		_ = f.Close()
	}, nil
}
