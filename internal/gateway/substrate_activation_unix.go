//go:build !windows

package gateway

import (
	"os"
	"syscall"
)

// SubstrateFileOwner is the owner uid of a file (stat).
func SubstrateFileOwner(info os.FileInfo) (uint32, bool) {
	st, ok := info.Sys().(*syscall.Stat_t)
	if !ok {
		return 0, false
	}
	return st.Uid, true
}
