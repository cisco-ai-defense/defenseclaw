const mergedTyped = "summarize this patient record"

// Claude Code merges consecutive user messages: agent blocks and the typed
// prompt arrive in one message. The router text is the typed prompt, with
// routing.context off and on, on the chat, passthrough and route-only paths.
var mergedShapes = map[string][]string{
	"local command": {"Caveat: The messages below were generated by the user while running local commands. DO NOT respond.",
		"<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>",
		"<local-command-stdout>Set model to SETMODEL</local-command-stdout>", mergedTyped},
	"bash mode":          {"<bash-input>ls</bash-input>", "<bash-stdout>BASHOUT.txt</bash-stdout><bash-stderr></bash-stderr>", mergedTyped},
	"ide file":           {"<ide_opened_file>The user opened IDEFILE.txt</ide_opened_file>", mergedTyped},
	"reminder one block": {"<system-reminder>REMINDER</system-reminder>" + mergedTyped},
	"custom command": {"<command-message>review is running</command-message>\n<command-name>/review</command-name>\n<command-args>" + mergedTyped + "</command-args>",
		"EXPANDED command file body"},
}

var mergedMarkers = []string{"Caveat", "command-", "SETMODEL", "BASHOUT", "IDEFILE", "REMINDER", "EXPANDED", "bash-input"}

func mergedBody(blocks []string) []byte {
	content := make([]map[string]string, 0, len(blocks))
	for _, b := range blocks {
		content = append(content, map[string]string{"type": "text", "text": b})
	}
	raw, _ := json.Marshal(map[string]any{"messages": []any{
		map[string]any{"role": "user", "content": "first ask"},
		map[string]any{"role": "assistant", "content": "ok"},
		map[string]any{"role": "user", "content": content},
	}})
	return raw
}

func TestRouterTextIsTheTypedPromptOfAMergedMessage(t *testing.T) {
	on := routeContextEngine(t, config.RoutingContextConfig{RecentUserTurns: 2})
	off := routeContextEngine(t, config.RoutingContextConfig{})
	for name, blocks := range mergedShapes {
		body := mergedBody(blocks)
		var parsed struct {
			Messages []ChatMessage `json:"messages"`
		}
		if err := json.Unmarshal(body, &parsed); err != nil {
			t.Fatal(err)
		}
		joined := parsed.Messages[2].Content // what lastUserText hands the passthrough
		routeOnly, _, _, _ := routeOnlyHumanText(config.RoutingAPIMessages, body)
		paths := map[string]*ModelRouterInput{
			"chat":        {Messages: parsed.Messages},
			"passthrough": {APIFamily: config.RoutingAPIMessages, Body: body, Text: passthroughRouterText(config.RoutingAPIMessages, body, joined)},
			"route-only":  {APIFamily: config.RoutingAPIMessages, Body: body, Text: routeOnly, Listener: engine.ListenerRouteOnly},
		}
		for path, in := range paths {
			for mode, eng := range map[string]*engine.Engine{"off": off, "on": on} {
				req := engineRequest(in)
				routeContext(eng, in, &req)
				seen := strings.Join(append([]string{req.Text}, req.ContextTurns...), "|")
				if req.Text != mergedTyped {
					t.Fatalf("%s %s context %s: router text %q, want the typed prompt", name, path, mode, req.Text)
				}
				if mode == "on" && !slices.Equal(req.ContextTurns, []string{"first ask"}) {
					t.Fatalf("%s %s: context %q", name, path, req.ContextTurns)
				}
				for _, bad := range mergedMarkers {
					if strings.Contains(seen, bad) {
						t.Fatalf("%s %s context %s: %s reached the router: %q", name, path, mode, bad, seen)
					}
				}
			}
		}
	}
}

// A tool_result turn gives the previous typed prompt with or without a
// reminder block on the passthrough path with routing.context off.
func TestPassthroughToolTurnWalksBackToTheTypedPrompt(t *testing.T) {
	loop := func(last string) []byte {
		return []byte(`{"messages":[{"role":"user","content":"` + mergedTyped + `"},
{"role":"assistant","content":[{"type":"tool_use","id":"t1","name":"Read","input":{}}]},
{"role":"user","content":[{"type":"tool_result","tool_use_id":"t1","content":"TOOL_OUTPUT"}` + last + `]}]}`)
	}
	for name, body := range map[string][]byte{
		"plain":    loop(""),
		"reminder": loop(`,{"type":"text","text":"<system-reminder>REMINDER</system-reminder>"}`),
	} {
		text := passthroughRouterText(config.RoutingAPIMessages, body, "<system-reminder>REMINDER</system-reminder>")
		req := engineRequest(&ModelRouterInput{APIFamily: config.RoutingAPIMessages, Body: body, Text: text})
		if req.Text != mergedTyped {
			t.Fatalf("%s: router text %q, want the previous typed prompt", name, req.Text)
		}
	}
}

func TestInjectedBlockAndCommandFilter(t *testing.T) {
	for text, want := range map[string]bool{
		"<bash-stdout>x</bash-stdout>": true, "<system-reminder>r</system-reminder><bash-stdout>x": true,
		"<SYSTEM-REMINDER>r</SYSTEM-REMINDER>typed": false, "<system-reminder>r</system-reminder>": false,
		"typed": false, "Contents of config.yaml look wrong": false,
	} {
		if got := injectedBlock(text); got != want {
			t.Errorf("injectedBlock(%q) = %v, want %v", text, got, want)
		}
	}
	if got := stripReminders("a<System-Reminder>x</SYSTEM-reminder>b"); got != "ab" {
		t.Errorf("stripReminders is case-sensitive: %q", got)
	}
	var f userBlockFilter
	var kept []string
	for _, b := range []string{"<command-name>/r</command-name><command-args>typed args</command-args>", "<system-reminder>x</system-reminder>", "expanded body", "later typed"} {
		if kt, ok := f.keep(b); ok {
			kept = append(kept, kt)
		}
	}
	if !slices.Equal(kept, []string{"typed args", "<system-reminder>x</system-reminder>", "later typed"}) {
		t.Fatalf("slash command blocks kept %q", kept)
	}
}
