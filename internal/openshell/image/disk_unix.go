//go:build !windows

package image

import (
	"io/fs"
	"syscall"
)

// allocatedBytes is the space a file takes on disk: its allocated blocks,
// which for a sparse file are far fewer than its size.
func allocatedBytes(info fs.FileInfo) int64 {
	if st, ok := info.Sys().(*syscall.Stat_t); ok {
		return int64(st.Blocks) * 512
	}
	return info.Size()
}
