package kernelpolicy

import (
	"errors"
	"os"
	"syscall"
)

// tryLock takes the reconciler lock without waiting. The kernel releases it
// when the holder exits, so a helper that died never leaves it behind.
func tryLock(dirs Dirs) (func(), error) {
	if err := os.MkdirAll(dirs.State, 0o700); err != nil {
		return nil, err
	}
	file, err := os.OpenFile(dirs.Lock(), os.O_RDWR|os.O_CREATE, 0o600)
	if err != nil {
		return nil, err
	}
	if err := syscall.Flock(int(file.Fd()), syscall.LOCK_EX|syscall.LOCK_NB); err != nil {
		_ = file.Close()
		if errors.Is(err, syscall.EWOULDBLOCK) {
			return nil, ErrReconcilerRunning
		}
		return nil, err
	}
	return func() {
		_ = syscall.Flock(int(file.Fd()), syscall.LOCK_UN)
		_ = file.Close()
	}, nil
}
