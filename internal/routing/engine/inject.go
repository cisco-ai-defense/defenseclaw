package engine

import "strings"

// injectedTags open blocks that agents put in user-role messages: Claude
// Code reminders, command and hook output, IDE context, Codex environment
// and instructions. A turn or content block that starts with one is not
// text the user typed.
var injectedTags = []string{
	"system-reminder", "environment_context", "user_instructions",
	"bash-stdout", "bash-stderr", "bash-input",
	"local-command-stdout", "local-command-stderr", "local-command-caveat",
	"command-name", "command-message", "command-args",
	"user-prompt-submit-hook", "task-notification", "ide_opened_file", "ide_selection",
	"user_shell_command",
}

// injectedPrefixes start agent-written user-role text: instruction files
// (Codex AGENTS.md, Claude Code CLAUDE.md), compaction summaries (Claude
// Code, Codex), skill loads, the local-command caveat and the OpenClaw
// context message. Case-sensitive, as the agents write them.
var injectedPrefixes = []string{
	"# AGENTS.md instructions", "# CLAUDE.md",
	"This session is being continued from a previous conversation",
	"Another language model started to solve this problem",
	"Base directory for this skill:",
	"Caveat: The messages below were generated by the user while running local commands",
	"<<<BEGIN_OPENCLAW_INTERNAL_CONTEXT>>>",
}

// instructionAttachment reports a Claude Code instruction attachment:
// "Contents of /path (project instructions...):" or "(user...". A typed
// sentence that starts with "Contents of" stays typed.
func instructionAttachment(t string) bool {
	rest, ok := strings.CutPrefix(t, "Contents of ")
	if !ok {
		return false
	}
	line, _, _ := strings.Cut(rest, "\n")
	return strings.Contains(line, "(project instructions") || strings.Contains(line, "(user") ||
		(strings.HasPrefix(line, "/") && strings.HasSuffix(strings.TrimSpace(line), ":"))
}

// StartsWithTag reports whether trimmed text t opens with the tag name
// (any case), followed by >, white space or /.
func StartsWithTag(t, tag string) bool {
	if len(t) <= len(tag)+1 || t[0] != 0x3c || !strings.EqualFold(t[1:1+len(tag)], tag) {
		return false
	}
	switch t[1+len(tag)] {
	case 0x3e, 0x20, 0x0a, 0x09, 0x0d, 0x2f: // > space newline tab return /
		return true
	}
	return false
}

// InjectedUserText reports whether user-role text was written by the agent
// rather than typed by the user, so the router never reads it. It is
// conservative: a known prefix or a known tag at the start is enough.
func InjectedUserText(s string) bool {
	t := strings.TrimSpace(s)
	if t == "" {
		return false
	}
	for _, p := range injectedPrefixes {
		if strings.HasPrefix(t, p) {
			return true
		}
	}
	if instructionAttachment(t) {
		return true
	}
	if t[0] != 0x3c { // <
		return false
	}
	for _, tag := range injectedTags {
		if StartsWithTag(t, tag) {
			return true
		}
	}
	return false
}
